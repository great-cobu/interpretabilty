% Generator script: Reads config.pl and outputs configs/generated/*.yaml
% Usage: swipl -q -t main -f prolog/gen_configs.pl

:- [config].

main :-
    validate_experiments,
    generate_all_experiment_configs,
    write('Successfully generated all experiment YAML configs in configs/generated/.\n'),
    halt(0).

generate_all_experiment_configs :-
    ensure_generated_dir(GenDir),
    forall(
        experiment_spec(ExpId, ModelId, DatasetId, RunName, Params),
        generate_experiment_yaml(GenDir, ExpId, ModelId, DatasetId, RunName, Params)
    ).

ensure_generated_dir(GenDir) :-
    (   exists_directory('configs')
    ->  GenDir = 'configs/generated'
    ;   exists_directory('../configs')
    ->  GenDir = '../configs/generated'
    ;   GenDir = 'configs/generated'
    ),
    (   exists_directory(GenDir)
    ->  true
    ;   make_directory(GenDir)
    ).

param_or_default(Key, Params, Default, Value) :-
    Term =.. [Key, Value],
    (   member(Term, Params)
    ->  true
    ;   Value = Default
    ).

model_dropout(logistic, 0.0).
model_dropout(mnist_cnn, 0.2).

generate_experiment_yaml(GenDir, ExpId, ModelId, DatasetId, RunName, Params) :-
    model_spec(ModelId, _, _, _, ExperimentName),
    dataset_spec(DatasetId, DataRoot, _, _, _, _),
    service_config(ml, mlflow_tracking_uri, TrackingURI),
    model_dropout(ModelId, Dropout),
    param_or_default(activation, Params, relu, Activation),
    param_or_default(epochs, Params, 1, Epochs),
    param_or_default(batch_size, Params, 256, BatchSize),
    param_or_default(learning_rate, Params, 0.001, LR),
    param_or_default(weight_decay, Params, 0.0, WeightDecay),
    experiment_run_dir(ExpId, RunDir),
    atomic_list_concat([GenDir, '/', ExpId, '.yaml'], TargetFile),
    open(TargetFile, write, Stream),
    format(Stream, "# Auto-generated by SWI-Prolog (prolog/gen_configs.pl) from prolog/config.pl~n", []),
    format(Stream, "# Do not edit by hand. Run ./scripts/gen_all.sh to regenerate.~n", []),
    format(Stream, "data:~n", []),
    format(Stream, "  directory: ~w~n", [DataRoot]),
    format(Stream, "  download: true~n", []),
    format(Stream, "  split_seed: 42~n", []),
    format(Stream, "  batch_size: ~w~n", [BatchSize]),
    format(Stream, "  num_workers: 0~n", []),
    format(Stream, "  mean: 0.1307~n", []),
    format(Stream, "  std: 0.3081~n", []),
    format(Stream, "  split_indices: null~n", []),
    format(Stream, "model:~n", []),
    format(Stream, "  dropout: ~w~n", [Dropout]),
    (   ModelId == mnist_cnn
    ->  format(Stream, "  activation: ~w~n", [Activation])
    ;   true
    ),
    format(Stream, "optimizer:~n", []),
    format(Stream, "  learning_rate: ~w~n", [LR]),
    format(Stream, "  weight_decay: ~w~n", [WeightDecay]),
    format(Stream, "trainer:~n", []),
    format(Stream, "  seed: 42~n", []),
    format(Stream, "  max_epochs: ~w~n", [Epochs]),
    format(Stream, "  accelerator: auto~n", []),
    format(Stream, "  devices: 1~n", []),
    format(Stream, "  precision: 32-true~n", []),
    format(Stream, "  deterministic: true~n", []),
    format(Stream, "  patience: 3~n", []),
    format(Stream, "  limit_train_batches: null~n", []),
    format(Stream, "  limit_val_batches: null~n", []),
    format(Stream, "tracking:~n", []),
    format(Stream, "  enabled: true~n", []),
    format(Stream, "  uri: ~w~n", [TrackingURI]),
    format(Stream, "  experiment_name: ~w~n", [ExperimentName]),
    format(Stream, "  run_name: ~w~n", [RunName]),
    format(Stream, "  tags:~n", []),
    format(Stream, "    model: ~w~n", [ModelId]),
    format(Stream, "    dataset: ~w~n", [DatasetId]),
    (   ModelId == mnist_cnn
    ->  format(Stream, "    activation: ~w~n", [Activation])
    ;   true
    ),
    format(Stream, "    managed_by: swi-prolog~n", []),
    format(Stream, "output_dir: ~w~n", [RunDir]),
    close(Stream).
